type normalizedField struct {
	GoName       string
	GoType       string
	DefaultType  string
	IsPK         bool
	IsRelationFK bool
	IsOptional   bool
	// Embedded names the embedded struct that promotes this field. Promoted
	// fields cannot be keyed directly in a composite literal, so defaults for
	// them are nested under the embedded struct's own literal.
	Embedded *embeddedStruct
}

// embeddedStruct identifies an anonymous struct field, such as gorm.Model.
type embeddedStruct struct {
	FieldName string // implicit field name, e.g. "Model"
	TypeExpr  string // type expression in the generated file, e.g. "gorm.Model"
}

type normalizedRelation struct {
	// HasMany marks the reverse side of another model's belongs-to relation;
	// LocalFields then name the FK fields on RefBlueprint.
	HasMany      bool
	Name         string
	LocalField   string
	LocalFields  []string
	RefField     string
	RefFields    []string
	RefBlueprint string
	Optional     bool
}

type normalizedMutationHook struct {
	Body string
}

type normalizedModel struct {
	// FieldName names the model's field in the generated Blueprints struct.
	FieldName     string
	StructName    string
	TypeExpr      string
	ZeroValueExpr string
	BlueprintID   string
	TableName     string
	PKFields      []string
	Fields        []normalizedField
	Relations     []normalizedRelation
	InsertHook    *normalizedMutationHook
	DeleteHook    *normalizedMutationHook
}

const normalizedStructTemplate = `
{{- range .}}
type {{.StructName}} struct {
{{- range .Fields}}
	{{.GoName}} {{.GoType}}
{{- end}}
}
{{ end }}
`

// generatedFileHeader marks the output as generated so that tools and readers
// leave it alone; customizations belong in a hand-written file of the package.
const generatedFileHeader = "// Code generated by seedling-gen. DO NOT EDIT.\n\n"

const normalizedBlueprintTemplate = `
// Blueprints holds the blueprints seedling-gen derives from the schema.
//
// Regenerating rewrites this file only. Keep project-specific Insert, Delete,
// Defaults, Traits, and extra Relations in a hand-written file that adjusts
// these fields before calling Register, so regeneration never overwrites them.
type Blueprints struct {
{{- range .}}
	{{.FieldName}} seedling.Blueprint[{{.TypeExpr}}]
{{- end}}
}

// NewBlueprints returns a fresh copy of every generated blueprint.
func NewBlueprints() Blueprints {
	return Blueprints{
{{- range $model := .}}
		{{$model.FieldName}}: seedling.Blueprint[{{$model.TypeExpr}}]{
			Name:  {{quote $model.BlueprintID}},
			Table: {{quote $model.TableName}},
{{- if isCompositePK $model}}
			PKFields: []string{ {{- range $i, $field := $model.PKFields}}{{if $i}}, {{end}}{{quote $field}}{{end}} },
{{- else if $model.PKFields}}
			PKField: {{quote (index $model.PKFields 0)}},
{{- end}}
			Defaults: func() {{$model.TypeExpr}} {
				return {{ defaultLiteral $model }}
			},
{{- if $model.Relations}}
			Relations: []seedling.Relation{
{{- range $model.Relations}}
				{Name: {{quote .Name}}, Kind: seedling.{{if .HasMany}}HasMany{{else}}BelongsTo{{end}}, {{- if isCompositeRelation .}} LocalFields: []string{ {{- range $i, $field := .LocalFields}}{{if $i}}, {{end}}{{quote $field}}{{end}} }, {{- else}} LocalField: {{quote .LocalField}}, {{- end}}{{- if .RefFields}}{{- if isCompositeReference .}} RefFields: []string{ {{- range $i, $field := .RefFields}}{{if $i}}, {{end}}{{quote $field}}{{end}} }, {{- else}} RefField: {{quote .RefField}}, {{- end}}{{- end}} RefBlueprint: {{quote .RefBlueprint}}{{- if .Optional}}, Optional: true{{- end}}},
{{- end}}
			},
{{- end}}
{{- if $model.InsertHook}}
			Insert: func(ctx context.Context, dbtx seedling.DBTX, v {{$model.TypeExpr}}) ({{$model.TypeExpr}}, error) {
{{ indent 4 $model.InsertHook.Body }}
			},
{{- else}}
			// Insert is not generated: set it in hand-written code before Register.
{{- end}}
{{- if $model.DeleteHook}}
			Delete: func(ctx context.Context, dbtx seedling.DBTX, v {{$model.TypeExpr}}) error {
{{ indent 4 $model.DeleteHook.Body }}
			},
{{- end}}
		},
{{- end}}
	}
}

// Register registers every blueprint in reg. It reports all blueprints that
// fail to register, such as those still missing an Insert callback.
func (b Blueprints) Register(reg *seedling.Registry) error {
	return errors.Join(
{{- range .}}
		seedling.RegisterTo(reg, b.{{.FieldName}}),
{{- end}}
	)
}

// MustRegister is like Register but panics if any blueprint fails to register.
func (b Blueprints) MustRegister(reg *seedling.Registry) {
	if err := b.Register(reg); err != nil {
		panic(err)
	}
}
`

func generateNormalizedCode(w io.Writer, kind, pkg string, imports []string, models []normalizedModel, emitStructs bool) error {
	models = withReverseRelations(models)
	if err := validateNormalizedModels(models, emitStructs); err != nil {
		return fmt.Errorf("validate %s generated code: %w", kind, err)
	}

	var buf strings.Builder

	buf.WriteString(generatedFileHeader)
	buf.WriteString("package ")
	buf.WriteString(pkg)
	buf.WriteString("\n\n")

	imports = append(imports, `"errors"`)
	if normalizedModelsNeedContextImport(models) {
		imports = append(imports, `"context"`)
	}
	if normalizedModelsNeedTimeImport(models, emitStructs) {
		imports = append(imports, `"time"`)
	}
	if err := validateImportNames(imports); err != nil {
		return fmt.Errorf("%s imports: %w", kind, err)
	}
	renderImports(&buf, imports)

	if emitStructs {
		structs, err := renderNormalizedTemplate("structs", normalizedStructTemplate, models, nil)
		if err != nil {
			return fmt.Errorf("render %s structs: %w", kind, err)
		}
		buf.WriteString(structs)
		buf.WriteString("\n")
	}

	blueprints, err := renderNormalizedTemplate("blueprints", normalizedBlueprintTemplate, models, template.FuncMap{
		"isCompositePK": func(model normalizedModel) bool {
			return len(model.PKFields) > 1
		},
		"isCompositeRelation": func(rel normalizedRelation) bool {
			return len(rel.LocalFields) > 1
		},
		"isCompositeReference": func(rel normalizedRelation) bool {
			return len(rel.RefFields) > 1
		},
		"defaultLiteral": buildDefaultLiteral,
		"indent":         indentBlock,
		"quote":          strconv.Quote,
	})
	if err != nil {
		return fmt.Errorf("render %s blueprints: %w", kind, err)
	}
	buf.WriteString(blueprints)

	formatted, err := format.Source([]byte(buf.String()))
	if err != nil {
		return fmt.Errorf("format %s generated code: %w", kind, err)
	}

	if _, err := w.Write(formatted); err != nil {
		return fmt.Errorf("write %s generated code: %w", kind, err)
	}

	return nil
}

// withReverseRelations adds to every model an optional has-many relation for
// each belongs-to relation that points at it, so tests can create children
// from the parent side with Ref and Count. The relations never expand by
// default; the zero Count keeps existing graphs unchanged.
//
// A relation is named after the plural child blueprint ("users"), qualified by
// the belongs-to relation name when that differs from the parent blueprint
// ("assignee_tasks"). A name already taken on the parent is left out rather
// than renaming a relation the schema author wrote.
func withReverseRelations(models []normalizedModel) []normalizedModel {
	byID := make(map[string]int, len(models))
	for i, model := range models {
		byID[model.BlueprintID] = i
	}

	out := slices.Clone(models)
	for i := range out {
		out[i].Relations = slices.Clone(out[i].Relations)
	}
	for _, child := range models {
		for _, rel := range child.Relations {
			if rel.HasMany {
				continue
			}
			parentIndex, ok := byID[rel.RefBlueprint]
			if !ok {
				continue
			}
			parent := &out[parentIndex]

			name := pluralize(child.BlueprintID)
			if rel.Name != parent.BlueprintID {
				name = rel.Name + "_" + name
			}
			if slices.ContainsFunc(parent.Relations, func(existing normalizedRelation) bool { return existing.Name == name }) {
				continue
			}
			parent.Relations = append(parent.Relations, normalizedRelation{
				HasMany:      true,
				Name:         name,
				LocalField:   rel.LocalField,
				LocalFields:  slices.Clone(rel.LocalFields),
				RefField:     rel.RefField,
				RefFields:    slices.Clone(rel.RefFields),
				RefBlueprint: child.BlueprintID,
				Optional:     true,
			})
		}
	}
	return out
}

// validateNormalizedModels guards against schema-derived identifiers and type
// expressions injecting arbitrary tokens into the generated source. Identifier
// positions must be valid Go identifiers, and type/expression positions must
// parse as a single Go expression so a crafted value cannot break out and
// append statements or fields. String-literal positions are escaped with
// strconv.Quote at render time and therefore need no validation here. This
// turns malformed input into a hard error instead of relying on format.Source
// to reject whatever the templates happen to emit.
func validateNormalizedModels(models []normalizedModel, emitStructs bool) error {
	fieldNames := make(map[string]struct{}, len(models))
	for _, model := range models {
		name := model.StructName
		if name == "" {
			name = model.TypeExpr
		}

		// FieldName becomes a field of the generated Blueprints struct, which
		// also carries the Register and MustRegister methods.
		if !token.IsIdentifier(model.FieldName) {
			return fmt.Errorf("model %q: invalid Blueprints field name %q", name, model.FieldName)
		}
		if _, reserved := reservedBlueprintsFieldNames[model.FieldName]; reserved {
			return fmt.Errorf("model %q: Blueprints field name %q collides with a generated method", name, model.FieldName)
		}
		if _, exists := fieldNames[model.FieldName]; exists {
			return fmt.Errorf("model %q: duplicate Blueprints field name %q", name, model.FieldName)
		}
		fieldNames[model.FieldName] = struct{}{}

		if err := validateGoExpr("type expression", model.TypeExpr); err != nil {
			return fmt.Errorf("model %q: %w", name, err)
		}
		if model.ZeroValueExpr != "" {
			if err := validateGoExpr("zero-value expression", model.ZeroValueExpr); err != nil {
				return fmt.Errorf("model %q: %w", name, err)
			}
		}

		if emitStructs && !token.IsIdentifier(model.StructName) {
			return fmt.Errorf("model %q: invalid struct name %q", name, model.StructName)
		}
		if _, reserved := reservedGeneratedNames[model.StructName]; emitStructs && reserved {
			return fmt.Errorf("model %q: struct name %q collides with a generated declaration", name, model.StructName)
		}

		for _, field := range model.Fields {
			if !token.IsIdentifier(field.GoName) {
				return fmt.Errorf("model %q: invalid field name %q", name, field.GoName)
			}
			if embedded := field.Embedded; embedded != nil {
				if !token.IsIdentifier(embedded.FieldName) {
					return fmt.Errorf("model %q field %q: invalid embedded field name %q", name, field.GoName, embedded.FieldName)
				}
				if err := validateGoExpr("embedded type", embedded.TypeExpr); err != nil {
					return fmt.Errorf("model %q field %q: %w", name, field.GoName, err)
				}
			}
			// GoType is only emitted as a type in the struct template.
			if emitStructs {
				if err := validateGoExpr("field type", field.GoType); err != nil {
					return fmt.Errorf("model %q field %q: %w", name, field.GoName, err)
				}
			}
		}
		relationNames := make(map[string]struct{}, len(model.Relations))
		for _, relation := range model.Relations {
			if relation.Name == "" {
				return fmt.Errorf("model %q: relation name must not be empty", name)
			}
			if _, exists := relationNames[relation.Name]; exists {
				return fmt.Errorf("model %q: duplicate relation name %q", name, relation.Name)
			}
			relationNames[relation.Name] = struct{}{}
			if len(relation.RefFields) > 0 && len(relation.RefFields) != len(relation.LocalFields) {
				return fmt.Errorf("model %q relation %q: %d local fields do not match %d referenced fields", name, relation.Name, len(relation.LocalFields), len(relation.RefFields))
			}
		}
	}
	return nil
}

// reservedGeneratedNames are the package-level identifiers the generated file
// declares besides the model structs.
var reservedGeneratedNames = map[string]struct{}{
	"Blueprints":    {},
	"NewBlueprints": {},
}

// reservedBlueprintsFieldNames are the methods declared on the generated
// Blueprints struct, which a field cannot share a name with.
var reservedBlueprintsFieldNames = map[string]struct{}{
	"Register":     {},
	"MustRegister": {},
}

// validateGoExpr reports whether expr parses as a single, complete Go
// expression. It is a breakout guard, not a type check: parser.ParseExpr
// rejects trailing tokens, so a crafted value cannot append statements or
// declarations after the expression, while the Go compiler still validates
// whether the expression is usable as a type when the generated code is built.
func validateGoExpr(label, expr string) error {
	if strings.TrimSpace(expr) == "" {
		return fmt.Errorf("empty %s", label)
	}
	if _, err := parser.ParseExpr(expr); err != nil {
		return fmt.Errorf("invalid %s %q: %w", label, expr, err)
	}
	return nil
}

// importSpec builds one import line with the path escaped via strconv.Quote and
// the alias (when present) validated as a Go identifier. Import paths and
// aliases come from CLI flags / tool config rather than the schema, but they
// reach the generated source through the same raw-concatenation path, so they
// are hardened the same way instead of trusting the caller-supplied string.
func importSpec(alias, path string) (string, error) {
	if alias != "" && !token.IsIdentifier(alias) {
		return "", fmt.Errorf("invalid import alias %q", alias)
	}
	if alias == "" {
		return strconv.Quote(path), nil
	}
	return alias + " " + strconv.Quote(path), nil
}

// validateImportNames rejects two imports that would bind the same package
// name, such as a models package named errors next to the standard library
// errors the generated code uses, which would otherwise yield code that does
// not compile.
func validateImportNames(imports []string) error {
	specsByName := make(map[string]string, len(imports))
	for _, spec := range uniqueStrings(imports) {
		name := importName(spec)
		if other, exists := specsByName[name]; exists {
			return fmt.Errorf("%s and %s both import as %q; use a package with a different name", other, spec, name)
		}
		specsByName[name] = spec
	}
	return nil
}

// importName returns the name an import spec binds: its alias, or otherwise
// the last element of its path.
func importName(spec string) string {
	if alias, _, ok := strings.Cut(spec, " "); ok {
		return alias
	}
	path, err := strconv.Unquote(spec)
	if err != nil {
		return spec
	}
	return path[strings.LastIndexByte(path, '/')+1:]
}

// renderImports groups standard library imports ahead of the rest, as
// goimports does by default, so the usual formatting leaves the generated file
// unchanged and --check keeps matching.
func renderImports(buf *strings.Builder, imports []string) {
	var std, external []string
	for _, imp := range uniqueStrings(imports) {
		if isStdlibImport(imp) {
			std = append(std, imp)
		} else {
			external = append(external, imp)
		}
	}

	buf.WriteString("import (\n")
	for i, group := range [][]string{std, external} {
		if i > 0 && len(std) > 0 && len(group) > 0 {
			buf.WriteString("\n")
		}
		for _, imp := range group {
			buf.WriteString("\t")
			buf.WriteString(imp)
			buf.WriteString("\n")
		}
	}
	buf.WriteString(")\n\n")
}

// isStdlibImport reports whether an import spec, optionally aliased, names a
// standard library package, whose first path element never contains a dot.
func isStdlibImport(spec string) bool {
	quoted := spec[strings.LastIndexByte(spec, ' ')+1:]
	path, err := strconv.Unquote(quoted)
	if err != nil {
		return false
	}
	first, _, _ := strings.Cut(path, "/")
	return !strings.Contains(first, ".")
}

func renderNormalizedTemplate(name, text string, data any, funcs template.FuncMap) (string, error) {
	tmpl := template.New(name)
	if funcs != nil {
		tmpl = tmpl.Funcs(funcs)
	}

	parsed, err := tmpl.Parse(text)
	if err != nil {
		return "", fmt.Errorf("parse %s template: %w", name, err)
	}

	var buf strings.Builder
	if err := parsed.Execute(&buf, data); err != nil {
		return "", fmt.Errorf("execute %s template: %w", name, err)
	}

	return buf.String(), nil
}

func indentBlock(level int, body string) string {
	if body == "" {
		return ""
	}

	prefix := strings.Repeat("\t", level)
	lines := strings.Split(strings.TrimRight(body, "\n"), "\n")
	for i, line := range lines {
		lines[i] = prefix + line
	}

	return strings.Join(lines, "\n") + "\n"
}

func uniqueStrings(values []string) []string {
	seen := make(map[string]struct{}, len(values))
	result := make([]string, 0, len(values))
	for _, value := range values {
		if _, ok := seen[value]; ok {
			continue
		}
		seen[value] = struct{}{}
		result = append(result, value)
	}
	return result
}

func normalizeTableModels(tables []Table) []normalizedModel {
	models := make([]normalizedModel, 0, len(tables))
	for _, table := range tables {
		fields := make([]normalizedField, 0, len(table.Columns))
		for _, column := range table.Columns {
			fields = append(fields, normalizedField{
				GoName:       column.GoName,
				GoType:       column.GoType,
				IsPK:         column.IsPK,
				IsRelationFK: column.IsFK,
				IsOptional:   !column.NotNull,
			})
		}

		// DDL alone does not say how the application writes rows, so Insert
		// stays unset and registration fails until hand-written code sets it.
		models = append(models, normalizedModel{
			FieldName:     table.GoName,
			StructName:    table.GoName,
			TypeExpr:      table.GoName,
			ZeroValueExpr: table.GoName + "{}",
			BlueprintID:   table.BlueprintID,
			TableName:     table.Name,
			PKFields:      normalizedPKFields(table.Columns),
			Fields:        fields,
			Relations:     normalizeTableRelations(table),
		})
	}
	return models
}

type sqlcTableBinding struct {
	model  *SqlcModel
	insert *SqlcQuery
	delete *SqlcDeleteQuery
}

func resolveSqlcTableBindings(tables []Table, info *SqlcInfo) (map[string]sqlcTableBinding, error) {
	bindings := make(map[string]sqlcTableBinding, len(tables))
	for _, table := range tables {
		binding, err := resolveSqlcTableBinding(table, info)
		if err != nil {
			return nil, fmt.Errorf("table %q: %w", table.Name, err)
		}
		bindings[table.Name] = binding
	}
	return bindings, nil
}

func resolveSqlcTableBinding(table Table, info *SqlcInfo) (sqlcTableBinding, error) {
	model, err := findUniqueSqlcModel(info.Models, table.GoName)
	if err != nil {
		return sqlcTableBinding{}, err
	}

	namedQueries := namedSqlcInsertQueries(info.Queries, table.GoName)
	if model == nil {
		if len(namedQueries) != 1 {
			return sqlcTableBinding{}, fmt.Errorf("sqlc model %q not found and %d Insert/Create queries identify the table", table.GoName, len(namedQueries))
		}
		if isSQLCQueryRow(*namedQueries[0]) {
			return sqlcTableBinding{}, fmt.Errorf(
				"query %q returns query-specific row type %q, which cannot identify the table model",
				namedQueries[0].Name,
				namedQueries[0].ReturnType,
			)
		}
		model, err = findUniqueSqlcModel(info.Models, namedQueries[0].ReturnType)
		if err != nil {
			return sqlcTableBinding{}, fmt.Errorf("query %q return type: %w", namedQueries[0].Name, err)
		}
		if model == nil {
			return sqlcTableBinding{}, fmt.Errorf("query %q returns unknown sqlc model %q", namedQueries[0].Name, namedQueries[0].ReturnType)
		}
	}

	matchingQueries := make([]*SqlcQuery, 0, len(info.Queries))
	for i := range info.Queries {
		if normalizeSQLCIdentifier(info.Queries[i].ReturnType) == normalizeSQLCIdentifier(model.Name) {
			matchingQueries = append(matchingQueries, &info.Queries[i])
		}
	}
	selectedInsert, hasInsert, err := selectSqlcInsertQuery(table, model, matchingQueries, namedQueries)
	if err != nil {
		return sqlcTableBinding{}, err
	}
	var insert *SqlcQuery
	if hasInsert {
		insert = &selectedInsert
	}

	deleteQuery, err := findUniqueSqlcDeleteQuery(info.DeleteQueries, table.GoName, model.Name)
	if err != nil {
		return sqlcTableBinding{}, err
	}
	return sqlcTableBinding{model: model, insert: insert, delete: deleteQuery}, nil
}

func isSQLCQueryRow(query SqlcQuery) bool {
	return normalizeSQLCIdentifier(query.ReturnType) == normalizeSQLCIdentifier(query.Name+"Row")
}

func findUniqueSqlcModel(models []SqlcModel, name string) (*SqlcModel, error) {
	for i := range models {
		if models[i].Name == name {
			return &models[i], nil
		}
	}

	wanted := normalizeSQLCIdentifier(name)
	var match *SqlcModel
	for i := range models {
		if normalizeSQLCIdentifier(models[i].Name) != wanted {
			continue
		}
		if match != nil {
			return nil, fmt.Errorf("sqlc model name %q is ambiguous", name)
		}
		match = &models[i]
	}
	return match, nil
}

func namedSqlcInsertQueries(queries []SqlcQuery, tableGoName string) []*SqlcQuery {
	insertName := normalizeSQLCIdentifier("Insert" + tableGoName)
	createName := normalizeSQLCIdentifier("Create" + tableGoName)
	matches := make([]*SqlcQuery, 0, 1)
	for i := range queries {
		name := normalizeSQLCIdentifier(queries[i].Name)
		if name == insertName || name == createName {
			matches = append(matches, &queries[i])
		}
	}
	return matches
}

func selectSqlcInsertQuery(table Table, model *SqlcModel, matching, named []*SqlcQuery) (SqlcQuery, bool, error) {
	if len(matching) == 1 {
		return *matching[0], true, nil
	}
	if len(matching) > 1 {
		var namedMatch *SqlcQuery
		for _, query := range matching {
			if !slices.Contains(named, query) {
				continue
			}
			if namedMatch != nil {
				return SqlcQuery{}, false, fmt.Errorf("multiple Insert/Create queries return sqlc model %q", model.Name)
			}
			namedMatch = query
		}
		if namedMatch != nil {
			return *namedMatch, true, nil
		}
		return SqlcQuery{}, false, fmt.Errorf("multiple queries return sqlc model %q", model.Name)
	}
	if len(named) > 0 {
		return SqlcQuery{}, false, fmt.Errorf("query %q does not return sqlc model %q for table %q", named[0].Name, model.Name, table.Name)
	}
	return SqlcQuery{}, false, nil
}

func findUniqueSqlcDeleteQuery(queries []SqlcDeleteQuery, tableGoName, modelName string) (*SqlcDeleteQuery, error) {
	targets := []string{
		normalizeSQLCIdentifier("Delete" + tableGoName),
		normalizeSQLCIdentifier("Delete" + modelName),
	}
	var match *SqlcDeleteQuery
	for i := range queries {
		if !slices.Contains(targets, normalizeSQLCIdentifier(queries[i].Name)) {
			continue
		}
		if match != nil && match.Name != queries[i].Name {
			return nil, fmt.Errorf("multiple delete queries match table model %q", modelName)
		}
		match = &queries[i]
	}
	return match, nil
}

func normalizeSqlcModels(tables []Table, sqlcInfo *SqlcInfo) ([]normalizedModel, error) {
	bindings, err := resolveSqlcTableBindings(tables, sqlcInfo)
	if err != nil {
		return nil, err
	}
	fieldMappings := make(map[string]map[string]SqlcField, len(tables))
	for _, table := range tables {
		sqlcModel := bindings[table.Name].model

		fieldsByColumn, err := mapSqlcModelFields(table, sqlcModel)
		if err != nil {
			return nil, fmt.Errorf("table %q model %q: %w", table.Name, sqlcModel.Name, err)
		}
		fieldMappings[table.Name] = fieldsByColumn
	}

	models := make([]normalizedModel, 0, len(tables))
	for _, table := range tables {
		binding := bindings[table.Name]
		fieldsByColumn := fieldMappings[table.Name]
		sqlcModel := binding.model
		pkFields, err := normalizedSqlcPKFields(table, fieldsByColumn)
		if err != nil {
			return nil, fmt.Errorf("table %q model %q: %w", table.Name, sqlcModel.Name, err)
		}
		relations, err := normalizeSqlcRelations(table, fieldMappings)
		if err != nil {
			return nil, fmt.Errorf("table %q model %q: %w", table.Name, sqlcModel.Name, err)
		}

		typePrefix := sqlcInfo.Package + "." + sqlcModel.Name
		model := normalizedModel{
			FieldName:     sqlcModel.Name,
			TypeExpr:      typePrefix,
			ZeroValueExpr: typePrefix + "{}",
			BlueprintID:   table.BlueprintID,
			TableName:     table.Name,
			PKFields:      pkFields,
			Fields:        normalizedSqlcFields(table, fieldsByColumn),
			Relations:     relations,
		}

		if query := binding.insert; query != nil {
			scalarField, err := resolveSqlcScalarInsertField(sqlcModel, *query, pkFields)
			if err != nil {
				return nil, fmt.Errorf("table %q query %q: %w", table.Name, query.Name, err)
			}
			paramFields, err := resolveSqlcParamFields(query.ParamFields, sqlcModel.Fields)
			if err != nil {
				return nil, fmt.Errorf("table %q query %q: %w", table.Name, query.Name, err)
			}
			model.InsertHook = &normalizedMutationHook{
				Body: buildSqlcInsertHook(sqlcInfo.Package, *query, paramFields, scalarField),
			}
		}

		if deleteQuery := binding.delete; deleteQuery != nil {
			paramFields, err := resolveSqlcParamFields(deleteQuery.ParamFields, sqlcModel.Fields)
			if err != nil {
				return nil, fmt.Errorf("table %q delete query %q: %w", table.Name, deleteQuery.Name, err)
			}
			scalarField, err := validateSqlcDeletePrimaryKey(
				*deleteQuery,
				paramFields,
				table,
				fieldsByColumn,
				model.PKFields,
			)
			if err != nil {
				return nil, fmt.Errorf("table %q delete query %q: %w", table.Name, deleteQuery.Name, err)
			}
			model.DeleteHook = &normalizedMutationHook{
				Body: buildSqlcDeleteHook(sqlcInfo.Package, *deleteQuery, paramFields, scalarField),
			}
		}

		models = append(models, model)
	}
	return models, nil
}

func normalizeGormModels(models []GormModel, alias string) []normalizedModel {
	normalized := make([]normalizedModel, 0, len(models))
	for _, model := range models {
		pkFields := make([]string, 0, len(model.Fields))
		for _, field := range model.Fields {
			if field.IsPK {
				pkFields = append(pkFields, field.Name)
			}
		}
		if len(pkFields) == 0 {
			pkFields = []string{"ID"}
		}

		relations := make([]normalizedRelation, 0, len(model.Fields))
		relationLocalFields := make(map[string]struct{})
		fieldsByName := make(map[string]GormField, len(model.Fields))
		for _, field := range model.Fields {
			fieldsByName[field.Name] = field
		}
		for _, field := range model.Fields {
			if field.Relation == nil || field.Relation.Kind != "BelongsTo" {
				continue
			}

			localFields := splitCommaSeparatedFields(field.Relation.ForeignKey)
			if len(localFields) == 0 {
				localFields = []string{field.Name + "ID"}
			}
			refFields := splitCommaSeparatedFields(field.Relation.References)

			required := true
			for _, localField := range localFields {
				fkField, ok := fieldsByName[localField]
				if !ok || !fkField.NotNull {
					required = false
					break
				}
			}

			relation := normalizedRelation{
				Name:         strings.ToLower(field.Name[:1]) + field.Name[1:],
				LocalFields:  localFields,
				RefFields:    refFields,
				RefBlueprint: singularize(strings.ToLower(field.Relation.RefModel)),
				Optional:     !required,
			}
			if len(localFields) == 1 {
				relation.LocalField = localFields[0]
			}
			if len(refFields) == 1 {
				relation.RefField = refFields[0]
			}
			relations = append(relations, relation)
			for _, localField := range localFields {
				relationLocalFields[localField] = struct{}{}
			}
		}

		fields := make([]normalizedField, 0, len(model.Fields))
		for _, field := range model.Fields {
			_, isRelationFK := relationLocalFields[field.Name]
			fields = append(fields, normalizedField{
				GoName: field.Name,
				GoType: field.Type,
				// GORM treats a field named ID as the primary key when no field
				// carries a primaryKey tag, so the inferred key must be left to
				// the database like an explicitly tagged one.
				IsPK:         slices.Contains(pkFields, field.Name),
				IsRelationFK: isRelationFK,
				IsOptional:   !field.NotNull,
				Embedded:     field.Embedded,
			})
		}

		normalized = append(normalized, normalizedModel{
			FieldName:     model.Name,
			TypeExpr:      alias + "." + model.Name,
			ZeroValueExpr: alias + "." + model.Name + "{}",
			BlueprintID:   singularize(strings.ToLower(model.Name)),
			TableName:     model.Table,
			PKFields:      pkFields,
			Fields:        fields,
			Relations:     relations,
			InsertHook: &normalizedMutationHook{
				Body: "if err := dbtx.(*gorm.DB).WithContext(ctx).Create(&v).Error; err != nil {\n\treturn v, err\n}\nreturn v, nil",
			},
			DeleteHook: &normalizedMutationHook{
				Body: "return dbtx.(*gorm.DB).WithContext(ctx).Delete(&v).Error",
			},
		})
	}
	return normalized
}

func splitCommaSeparatedFields(value string) []string {
	fields := make([]string, 0, strings.Count(value, ",")+1)
	for field := range strings.SplitSeq(value, ",") {
		if field = strings.TrimSpace(field); field != "" {
			fields = append(fields, field)
		}
	}
	return fields
}

func normalizeEntModels(schemas []EntSchema) []normalizedModel {
	models := make([]normalizedModel, 0, len(schemas))
	for _, schema := range schemas {
		model := normalizedModel{
			FieldName:     schema.Name,
			TypeExpr:      "*ent." + schema.Name,
			ZeroValueExpr: "&ent." + schema.Name + "{}",
			BlueprintID:   singularize(strings.ToLower(schema.Name)),
			TableName:     singularize(strings.ToLower(schema.Name)) + "s",
			PKFields:      []string{"ID"},
			Fields:        normalizeEntFields(schema.Fields, []string{"ID"}),
		}

		for _, edge := range schema.Edges {
			if edge.Field == "" {
				continue
			}

			field, _ := lookupEntField(schema.Fields, edge.Field)
			localField := field.GoName
			for i := range model.Fields {
				if model.Fields[i].GoName == localField {
					model.Fields[i].IsRelationFK = true
					break
				}
			}
			model.Relations = append(model.Relations, normalizedRelation{
				Name:         edge.Name,
				LocalField:   localField,
				LocalFields:  []string{localField},
				RefBlueprint: singularize(strings.ToLower(edge.Type)),
				Optional:     !edge.Required,
			})
		}

		model.InsertHook = &normalizedMutationHook{
			Body: buildEntInsertHook(schema),
		}
		model.DeleteHook = &normalizedMutationHook{
			Body: "return dbtx.(*ent.Client)." + schema.Name + ".DeleteOneID(v.ID).Exec(ctx)",
		}

		models = append(models, model)
	}
	return models
}

// normalizedPKFields returns the declared primary key columns, falling back to
// a conventional id column. A table with neither gets no key, so the generated
// blueprint never names a field its struct lacks.
func normalizedPKFields(columns []Column) []string {
	fields := make([]string, 0, len(columns))
	for _, column := range columns {
		if column.IsPK {
			fields = append(fields, column.GoName)
		}
	}
	if len(fields) > 0 {
		return fields
	}
	for _, column := range columns {
		if strings.EqualFold(column.Name, "id") {
			return []string{column.GoName}
		}
	}
	return nil
}

// mapSqlcModelFields pairs each schema column with the struct field sqlc
// generated for it.
//
// sqlc emits model fields in table column order, so position is the binding, and
// a column whose name sqlc rewrote (the `rename` config option) still resolves.
// Position is verified rather than assumed: if a column's name matches a field at
// some other index, this schema and that model disagree about the column order,
// and binding by position would make the generated hooks read and delete by the
// wrong column while still compiling.
func mapSqlcModelFields(table Table, model *SqlcModel) (map[string]SqlcField, error) {
	if len(model.Fields) != len(table.Columns) {
		return nil, fmt.Errorf("has %d fields but schema table has %d columns", len(model.Fields), len(table.Columns))
	}

	fieldIndexes := unambiguousSqlcFieldIndexes(model.Fields)
	fieldsByColumn := make(map[string]SqlcField, len(table.Columns))
	for i, column := range table.Columns {
		if j, ok := fieldIndexes[normalizeSQLCIdentifier(column.Name)]; ok && j != i {
			return nil, fmt.Errorf("column %q matches generated field %q at position %d, but position %d holds %q; regenerate sqlc so its models match this schema",
				column.Name, model.Fields[j].Name, j, i, model.Fields[i].Name)
		}
		fieldsByColumn[column.Name] = model.Fields[i]
	}

	return fieldsByColumn, nil
}

// unambiguousSqlcFieldIndexes indexes fields by normalized name, dropping any
// name that more than one field normalizes to so an ambiguous match never drives
// the position check.
func unambiguousSqlcFieldIndexes(fields []SqlcField) map[string]int {
	indexes := make(map[string]int, len(fields))
	ambiguous := make(map[string]struct{})
	for j, field := range fields {
		name := normalizeSQLCIdentifier(field.Name)
		if _, exists := indexes[name]; exists {
			ambiguous[name] = struct{}{}
			continue
		}
		indexes[name] = j
	}
	for name := range ambiguous {
		delete(indexes, name)
	}
	return indexes
}

func normalizedSqlcFields(table Table, fieldsByColumn map[string]SqlcField) []normalizedField {
	fields := make([]normalizedField, 0, len(table.Columns))
	for _, column := range table.Columns {
		field := fieldsByColumn[column.Name]
		fields = append(fields, normalizedField{
			GoName:       field.Name,
			GoType:       field.Type,
			IsPK:         column.IsPK,
			IsRelationFK: column.IsFK,
			IsOptional:   !column.NotNull,
		})
	}
	return fields
}

func normalizedSqlcPKFields(table Table, fieldsByColumn map[string]SqlcField) ([]string, error) {
	fields := make([]string, 0, len(table.Columns))
	for _, column := range table.Columns {
		if column.IsPK {
			fields = append(fields, fieldsByColumn[column.Name].Name)
		}
	}
	if len(fields) > 0 {
		return fields, nil
	}

	for _, column := range table.Columns {
		if normalizeSQLCIdentifier(column.Name) == "id" {
			return []string{fieldsByColumn[column.Name].Name}, nil
		}
	}
	return nil, fmt.Errorf("has no primary key and no conventional id field")
}

func normalizeSqlcRelations(table Table, fieldMappings map[string]map[string]SqlcField) ([]normalizedRelation, error) {
	relations := make([]normalizedRelation, 0, len(table.ForeignKeys))
	names := relationNamesForTable(table)
	for i, foreignKey := range table.ForeignKeys {
		if len(foreignKey.Columns) == 0 {
			continue
		}
		name := names[i]

		localFields := make([]string, 0, len(foreignKey.Columns))
		for _, columnName := range foreignKey.Columns {
			field, ok := fieldMappings[table.Name][columnName]
			if !ok {
				return nil, fmt.Errorf("relation %q: local column %q not found", name, columnName)
			}
			localFields = append(localFields, field.Name)
		}

		refFields := make([]string, 0, len(foreignKey.RefColumns))
		if len(foreignKey.RefColumns) > 0 {
			refMapping, ok := fieldMappings[foreignKey.RefTable]
			if !ok {
				return nil, fmt.Errorf("relation %q: referenced table %q is not present in sqlc models", name, foreignKey.RefTable)
			}
			for _, columnName := range foreignKey.RefColumns {
				field, ok := refMapping[columnName]
				if !ok {
					return nil, fmt.Errorf("relation %q: referenced column %q.%s not found", name, foreignKey.RefTable, columnName)
				}
				refFields = append(refFields, field.Name)
			}
		}

		relation := normalizedRelation{
			Name:         name,
			LocalFields:  localFields,
			RefFields:    refFields,
			RefBlueprint: singularize(foreignKey.RefTable),
			Optional:     !foreignKey.NotNull,
		}
		if len(localFields) == 1 {
			relation.LocalField = localFields[0]
		}
		if len(refFields) == 1 {
			relation.RefField = refFields[0]
		}
		relations = append(relations, relation)
	}
	return relations, nil
}

func normalizeEntFields(fields []EntField, pkFields []string) []normalizedField {
	normalized := make([]normalizedField, 0, len(fields))
	for _, field := range fields {
		goName := field.GoName
		if goName == "" {
			// Only the diagnostic fallback path reaches here, where the
			// generated package could not be resolved.
			goName = toGoFieldName(field.Name)
		}
		normalized = append(normalized, normalizedField{
			GoName:      goName,
			GoType:      field.GoType,
			DefaultType: field.DefaultType,
			// A schema that declares its own id (field.Int("id")) surfaces as an
			// ordinary field. Marking it as the primary key keeps generated
			// Defaults from overwriting the ID that Ent or the database assigns.
			IsPK:       slices.Contains(pkFields, goName),
			IsOptional: field.Optional || field.Nillable,
		})
	}
	return normalized
}

func normalizeTableRelations(table Table) []normalizedRelation {
	relations := make([]normalizedRelation, 0, len(table.ForeignKeys))
	names := relationNamesForTable(table)
	for i, foreignKey := range table.ForeignKeys {
		if len(foreignKey.Columns) == 0 {
			continue
		}
		name := names[i]

		localFields := make([]string, 0, len(foreignKey.Columns))
		for _, columnName := range foreignKey.Columns {
			for _, column := range table.Columns {
				if column.Name != columnName {
					continue
				}
				localFields = append(localFields, column.GoName)
				break
			}
		}
		if len(localFields) == 0 {
			continue
		}

		refFields := make([]string, 0, len(foreignKey.RefColumns))
		for _, columnName := range foreignKey.RefColumns {
			refFields = append(refFields, toGoFieldName(columnName))
		}

		relation := normalizedRelation{
			Name:         name,
			LocalFields:  localFields,
			RefFields:    refFields,
			RefBlueprint: singularize(foreignKey.RefTable),
			Optional:     !foreignKey.NotNull,
		}
		if len(localFields) == 1 {
			relation.LocalField = localFields[0]
		}
		if len(refFields) == 1 {
			relation.RefField = refFields[0]
		}

		relations = append(relations, relation)
	}
	return relations
}

func buildDefaultLiteral(model normalizedModel) string {
	prefix, ok := strings.CutSuffix(model.ZeroValueExpr, "{}")
	if !ok {
		return model.ZeroValueExpr
	}

	// Promoted fields are grouped under their embedded struct, which takes the
	// position of its first defaulted field.
	type literalEntry struct {
		embedded *embeddedStruct
		parts    []string
	}
	var entries []*literalEntry
	embeddedEntries := make(map[embeddedStruct]*literalEntry)
	for _, field := range model.Fields {
		expr := defaultFieldExpr(model.BlueprintID, field)
		if expr == "" {
			continue
		}
		assignment := field.GoName + ": " + expr
		if field.Embedded == nil {
			entries = append(entries, &literalEntry{parts: []string{assignment}})
			continue
		}
		entry, ok := embeddedEntries[*field.Embedded]
		if !ok {
			entry = &literalEntry{embedded: field.Embedded}
			embeddedEntries[*field.Embedded] = entry
			entries = append(entries, entry)
		}
		entry.parts = append(entry.parts, assignment)
	}
	if len(entries) == 0 {
		return model.ZeroValueExpr
	}

	assignments := make([]string, 0, len(entries))
	for _, entry := range entries {
		if entry.embedded == nil {
			assignments = append(assignments, entry.parts[0])
			continue
		}
		assignments = append(assignments, entry.embedded.FieldName+": "+entry.embedded.TypeExpr+"{"+strings.Join(entry.parts, ", ")+"}")
	}
	return prefix + "{" + strings.Join(assignments, ", ") + "}"
}

// timeDefaultExpr is the generated default for time.Time fields.
const timeDefaultExpr = "time.Date(2024, time.January, 1, 0, 0, 0, 0, time.UTC)"

func defaultFieldExpr(blueprintID string, field normalizedField) string {
	if field.IsPK || field.IsRelationFK {
		return ""
	}

	label := blueprintID + "-" + toSnakeCase(field.GoName)

	fieldType := field.GoType
	if field.DefaultType != "" {
		fieldType = field.DefaultType
	}

	switch fieldType {
	case "string":
		return strconv.Quote(label)
	case "bool":
		return "true"
	case "int", "int8", "int16", "int32", "int64",
		"uint", "uint8", "uint16", "uint32", "uint64",
		"float32", "float64":
		return "1"
	case "[]byte":
		return "[]byte(" + strconv.Quote(label) + ")"
	case "time.Time":
		return timeDefaultExpr
	default:
		return ""
	}
}

// normalizedModelsNeedContextImport reports whether any generated Insert or
// Delete callback takes a context.
func normalizedModelsNeedContextImport(models []normalizedModel) bool {
	return slices.ContainsFunc(models, func(model normalizedModel) bool {
		return model.InsertHook != nil || model.DeleteHook != nil
	})
}

// normalizedModelsNeedTimeImport reports whether the generated file references
// the time package: through emitted struct field types, or through a default
// that is actually rendered. A time.Time field skipped by the defaults (a key or
// relation field) on an existing model type needs no import.
func normalizedModelsNeedTimeImport(models []normalizedModel, emitStructs bool) bool {
	for _, model := range models {
		for _, field := range model.Fields {
			if emitStructs && field.GoType == "time.Time" {
				return true
			}
			if defaultFieldExpr(model.BlueprintID, field) == timeDefaultExpr {
				return true
			}
		}
	}
	return false
}

type sqlcParamField struct {
	paramName  string
	modelField string
}

// resolveSqlcParamFields binds each params-struct field to the model field the
// generated Insert hook should read it from.
//
// Name matches are resolved first, across every parameter, before any type-only
// fallback claims a field. Resolving in parameter order instead let a fallback
// consume a field that a later parameter matched by name, which then failed with
// a misleading "maps to model field more than once".
func resolveSqlcParamFields(params, modelFields []SqlcField) ([]sqlcParamField, error) {
	matches := make([]int, len(params))
	for i := range matches {
		matches[i] = -1
	}
	used := make([]bool, len(modelFields))

	for i, param := range params {
		match, matched, err := matchSqlcParamFieldByName(param, modelFields, used)
		if err != nil {
			return nil, err
		}
		if !matched {
			continue
		}
		used[match] = true
		matches[i] = match
	}

	for i, param := range params {
		if matches[i] >= 0 {
			continue
		}
		match, err := matchSqlcParamFieldByType(param, modelFields, used)
		if err != nil {
			return nil, err
		}
		used[match] = true
		matches[i] = match
	}

	resolved := make([]sqlcParamField, 0, len(params))
	for i, param := range params {
		resolved = append(resolved, sqlcParamField{
			paramName:  param.Name,
			modelField: modelFields[matches[i]].Name,
		})
	}
	return resolved, nil
}

// matchSqlcParamFieldByName resolves a parameter against a model field of the
// same name, exactly or ignoring case and underscores. It reports whether a name
// match existed at all, so the caller can defer to the type fallback.
func matchSqlcParamFieldByName(param SqlcField, modelFields []SqlcField, used []bool) (int, bool, error) {
	for i, field := range modelFields {
		if field.Name != param.Name {
			continue
		}
		if used[i] {
			return 0, false, fmt.Errorf("params field %q maps to model field %q more than once", param.Name, field.Name)
		}
		if field.Type != param.Type {
			return 0, false, fmt.Errorf("params field %q type %s does not match model field type %s", param.Name, param.Type, field.Type)
		}
		return i, true, nil
	}

	normalizedMatches := make([]int, 0, 1)
	for i, field := range modelFields {
		if normalizeSQLCIdentifier(field.Name) == normalizeSQLCIdentifier(param.Name) {
			normalizedMatches = append(normalizedMatches, i)
		}
	}
	if len(normalizedMatches) > 1 {
		return 0, false, fmt.Errorf("params field %q matches multiple model fields by name", param.Name)
	}
	if len(normalizedMatches) == 0 {
		return 0, false, nil
	}

	match := normalizedMatches[0]
	if used[match] {
		return 0, false, fmt.Errorf("params field %q maps to model field %q more than once", param.Name, modelFields[match].Name)
	}
	if modelFields[match].Type != param.Type {
		return 0, false, fmt.Errorf("params field %q type %s does not match model field %q type %s", param.Name, param.Type, modelFields[match].Name, modelFields[match].Type)
	}
	return match, true, nil
}

// matchSqlcParamFieldByType handles a query parameter that sqlc named after
// nothing in the model. It only resolves when exactly one unclaimed field has the
// right type, because anything less specific would be a guess.
func matchSqlcParamFieldByType(param SqlcField, modelFields []SqlcField, used []bool) (int, error) {
	typeMatches := make([]int, 0, 1)
	for i, field := range modelFields {
		if !used[i] && field.Type == param.Type {
			typeMatches = append(typeMatches, i)
		}
	}
	if len(typeMatches) == 1 {
		return typeMatches[0], nil
	}
	return 0, fmt.Errorf("cannot map params field %q (%s) to exactly one model field", param.Name, param.Type)
}

func validateSqlcDeletePrimaryKey(
	query SqlcDeleteQuery,
	paramFields []sqlcParamField,
	table Table,
	fieldsByColumn map[string]SqlcField,
	pkFields []string,
) (string, error) {
	if query.ParamType != "" {
		seen := make(map[string]struct{}, len(paramFields))
		for _, field := range paramFields {
			if !slices.Contains(pkFields, field.modelField) {
				return "", fmt.Errorf(
					"params field %q maps to non-primary-key model field %q",
					field.paramName,
					field.modelField,
				)
			}
			if _, ok := seen[field.modelField]; ok {
				return "", fmt.Errorf("primary-key model field %q is mapped more than once", field.modelField)
			}
			seen[field.modelField] = struct{}{}
		}
		for _, pkField := range pkFields {
			if _, ok := seen[pkField]; !ok {
				return "", fmt.Errorf("does not accept primary-key model field %q", pkField)
			}
		}
		return "", nil
	}

	if query.ArgType == "" {
		return "", fmt.Errorf("does not accept the model primary key")
	}
	if len(pkFields) != 1 {
		return "", fmt.Errorf("scalar argument cannot cover %d primary-key fields", len(pkFields))
	}

	pkField := pkFields[0]
	if query.ArgName != "" && query.ArgName != "_" {
		argumentField, err := resolveSqlcDeleteArgumentField(query.ArgName, table, fieldsByColumn)
		if err != nil {
			return "", err
		}
		if argumentField != pkField {
			return "", fmt.Errorf(
				"scalar argument %q identifies non-primary-key model field %q",
				query.ArgName,
				argumentField,
			)
		}
	}

	for _, field := range fieldsByColumn {
		if field.Name != pkField {
			continue
		}
		if field.Type != query.ArgType {
			return "", fmt.Errorf(
				"scalar argument %q type %s does not match primary-key model field %q type %s",
				query.ArgName,
				query.ArgType,
				pkField,
				field.Type,
			)
		}
		return pkField, nil
	}
	return "", fmt.Errorf("primary-key model field %q is missing from sqlc model", pkField)
}

func resolveSqlcDeleteArgumentField(
	argumentName string,
	table Table,
	fieldsByColumn map[string]SqlcField,
) (string, error) {
	wanted := normalizeSQLCIdentifier(argumentName)
	matches := make(map[string]struct{}, 1)
	for _, column := range table.Columns {
		field := fieldsByColumn[column.Name]
		if normalizeSQLCIdentifier(column.Name) == wanted || normalizeSQLCIdentifier(field.Name) == wanted {
			matches[field.Name] = struct{}{}
		}
	}
	if len(matches) == 0 {
		return "", fmt.Errorf("scalar argument %q does not identify a model field", argumentName)
	}
	if len(matches) > 1 {
		return "", fmt.Errorf("scalar argument %q identifies multiple model fields", argumentName)
	}
	for field := range matches {
		return field, nil
	}
	panic("unreachable")
}

func buildSqlcInsertHook(alias string, query SqlcQuery, paramFields []sqlcParamField, scalarField string) string {
	var body strings.Builder
	if query.ReturnPointer {
		body.WriteString("inserted, err := ")
	} else {
		body.WriteString("return ")
	}
	writeSqlcQueriesConstructor(&body, alias, query.DBArgument)
	body.WriteString(query.Name)
	body.WriteString("(ctx")
	if query.DBArgument {
		body.WriteString(", dbtx.(")
		body.WriteString(alias)
		body.WriteString(".DBTX)")
	}
	switch {
	case query.ParamType != "":
		body.WriteString(", ")
		if query.ParamPointer {
			body.WriteString("&")
		}
		body.WriteString(alias)
		body.WriteString(".")
		body.WriteString(query.ParamType)
		body.WriteString("{\n")
		for _, field := range paramFields {
			body.WriteString("\t")
			body.WriteString(field.paramName)
			body.WriteString(": v.")
			body.WriteString(field.modelField)
			body.WriteString(",\n")
		}
		body.WriteString("}")
	case query.ArgType != "":
		body.WriteString(", v.")
		body.WriteString(scalarField)
	}
	body.WriteString(")")
	if query.ReturnPointer {
		body.WriteString("\nif err != nil {\n\treturn v, err\n}\nreturn *inserted, nil")
	}
	return body.String()
}

func resolveSqlcScalarInsertField(model *SqlcModel, query SqlcQuery, pkFields []string) (string, error) {
	if query.ParamType != "" || query.ArgType == "" {
		return "", nil
	}

	type candidate struct {
		name       string
		typeName   string
		primaryKey bool
	}
	isPrimaryKey := func(name string) bool {
		return slices.Contains(pkFields, name)
	}

	candidates := make([]candidate, 0, len(model.Fields))
	for _, field := range model.Fields {
		candidates = append(candidates, candidate{
			name:       field.Name,
			typeName:   field.Type,
			primaryKey: isPrimaryKey(field.Name),
		})
	}

	if query.ArgName != "" && query.ArgName != "_" {
		normalizedArgument := normalizeSQLCIdentifier(query.ArgName)
		for _, candidate := range candidates {
			if normalizeSQLCIdentifier(candidate.name) == normalizedArgument {
				return candidate.name, nil
			}
		}
	}

	typeMatches := make([]candidate, 0, len(candidates))
	nonPKMatches := make([]candidate, 0, len(candidates))
	for _, candidate := range candidates {
		if candidate.typeName != query.ArgType {
			continue
		}
		typeMatches = append(typeMatches, candidate)
		if !candidate.primaryKey {
			nonPKMatches = append(nonPKMatches, candidate)
		}
	}
	if len(nonPKMatches) == 1 {
		return nonPKMatches[0].name, nil
	}
	if len(typeMatches) == 1 {
		return typeMatches[0].name, nil
	}

	return "", fmt.Errorf("cannot map scalar argument %q (%s) to exactly one model field", query.ArgName, query.ArgType)
}

func normalizeSQLCIdentifier(value string) string {
	return strings.ToLower(strings.ReplaceAll(value, "_", ""))
}

